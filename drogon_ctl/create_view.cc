static std::string cppStr(const std::string &s)
{
    std::string trimmed{drogon::utils::trim(s)};
    std::string res;
    res.reserve(trimmed.size() * 2);
    for (char c : trimmed)
    {
        switch (c)
        {
            case '\\':
                res += "\\\\";
                break;
            case '"':
                res += "\\\"";
                break;
            default:
                res += c;
        }
    }
    return res;
}

static std::string headers(const std::string &filename)
{
    return "// this file is generated by program(drogon_ctl) automatically, "
           "don't modify it!\n"
           "#include \"" +
           filename + "." + headerExtension +
           "\"\n\n"
           "#include <drogon/utils/OStringStream.h>\n"
           "#include <drogon/utils/Utilities.h>\n"
           "#include <string>\n"
           "#include <map>\n"
           "#include <vector>\n"
           "#include <set>\n"
           "#include <iostream>\n"
           "#include <unordered_map>\n"
           "#include <unordered_set>\n"
           "#include <algorithm>\n"
           "#include <list>\n"
           "#include <deque>\n"
           "#include <queue>\n";
}

enum class NodeType : uint8_t
{
    NormalText,
    Include,
    CppCode,
    OutPut1,  // [[ parameter_name ]]
    OutPut2,  // {% cpp code %}
    Layout,
    View,
};

struct Node
{
    std::string content;
    NodeType type;

    Node(std::string content, NodeType type)
        : content(std::move(content)), type(type)
    {
    }
};

struct TokenRule
{
    std::string_view start;
    std::string_view end;
    NodeType type;
};

static void outputEscapedText(std::ofstream &file,
                              std::string_view content,
                              const std::string &streamName)
{
    static const std::pair<std::string_view, std::string_view> escapeRules[] = {
        {"\\<%c++", "<%c++"},
        {"\\<%inc", "<%inc"},
        {"\\[[", "[["},
        {"\\{%", "{%"},
        {"\\<%layout", "<%layout"},
        {"\\<%view", "<%view"},
        {"\\<%filetype", "<%filetype"},
    };

    file << "\t" << streamName << " << \"";
    size_t i = 0;
    const size_t len = content.size();

    while (i < len)
    {
        char ch = content[i];
        bool matched = false;

        if (ch == '\\')
        {
            for (const auto [prefix, repl] : escapeRules)
            {
                if (i + prefix.size() <= len &&
                    content.substr(i, prefix.size()) == prefix)
                {
                    file << repl;
                    i += prefix.size();
                    matched = true;
                    break;
                }
            }
            if (matched)
                continue;
        }

        switch (ch)
        {
            case '\\':
                file << "\\\\";
                break;
            case '"':
                file << "\\\"";
                break;
            case '\t':
                file << "\\t";
                break;
            default:
                file << ch;
        }
        i++;
    }
    file << "\\n\";\n";
}

static void outputNormalText(std::ofstream &file,
                             std::string_view content,
                             const std::string &streamName)
{
    size_t pos = 0;
    while (pos < content.size())
    {
        auto next = content.find('\n', pos);
        if (next == std::string_view::npos)
        {
            outputEscapedText(file, content.substr(pos), streamName);
            break;
        }
        size_t end = next;
        if (end > pos && content[end - 1] == '\r')
        {
            end -= 1;
        }
        outputEscapedText(file, content.substr(pos, end - pos), streamName);
        pos = next + 1;
    }
}

void outputNode(std::ofstream &file,
                Node &node,
                const std::string &streamName = "",
                const std::string &viewDataName = "")
{
    switch (node.type)
    {
        case NodeType::NormalText:
            outputNormalText(file, node.content, streamName);
            break;

        case NodeType::Include:
            drogon::utils::replaceAll(node.content, "\\%>", "%>");
            file << node.content << "\n";
            break;

        case NodeType::CppCode:
        {
            drogon::utils::replaceAll(node.content, "\\%>", "%>");
            const std::string &src = node.content;
            for (size_t i = 0; i < src.size(); ++i)
            {
                if (i + 1 < src.size())
                {
                    if (src[i] == '$' && src[i + 1] == '$')
                    {
                        file << streamName;
                        ++i;
                        continue;
                    }
                    else if (src[i] == '@' && src[i + 1] == '@')
                    {
                        file << viewDataName;
                        ++i;
                        continue;
                    }
                }
                file << src[i];
            }
            file << "\n";
            break;
        }

        case NodeType::OutPut1:
        {
            if (node.content.find("\n") != std::string::npos)
            {
                std::cerr << "ERROR: [[ ]] must be on the same line"
                          << std::endl;
                exit(1);
            }
            drogon::utils::replaceAll(node.content, "\\]]", "]]");
            auto key = cppStr(node.content);
            file << "\t{\n"
                 << "\t\tauto &val = " << viewDataName << "[\"" << key
                 << "\"];\n"
                 << "\t\tif (val.type() == typeid(const char *)) {\n"
                 << "\t\t\t" << streamName
                 << "<<*(std::any_cast<const char *>(&val));\n"
                 << "\t\t} else if (val.type() == typeid(std::string) || "
                    "val.type() == typeid(const std::string)) {\n"
                 << "\t\t\t" << streamName
                 << "<< *(std::any_cast<const std::string>(&val));\n"
                 << "\t\t}\n"
                 << "\t}\n";
            break;
        }

        case NodeType::OutPut2:
        {
            if (node.content.find("\n") != std::string::npos)
            {
                std::cerr << "ERROR: {% %} must be on the same line"
                          << std::endl;
                exit(1);
            }

            file << "\t" << streamName << " << ";
            drogon::utils::replaceAll(node.content, "\\%}", "%}");
            std::string expr{drogon::utils::trim(node.content)};
            for (size_t i = 0; i < expr.size(); ++i)
            {
                if (i + 1 < expr.size())
                {
                    if (expr[i] == '$' && expr[i + 1] == '$')
                    {
                        file << streamName;
                        ++i;
                        continue;
                    }
                    else if (expr[i] == '@' && expr[i + 1] == '@')
                    {
                        file << viewDataName;
                        ++i;
                        continue;
                    }
                }
                file << expr[i];
            }
            file << ";\n";
            break;
        }

        case NodeType::View:
        {
            if (node.content.find("\n") != std::string::npos)
            {
                std::cerr << "ERROR: <%view %> must be on the same line"
                          << std::endl;
                exit(1);
            }
            drogon::utils::replaceAll(node.content, "\\%>", "%>");
            auto viewName = cppStr(node.content);
            file << "\t{\n"
                 << "\t\tauto templ = DrTemplateBase::newTemplate(\""
                 << viewName << "\");\n"
                 << "\t\tif (templ) {\n"
                 << "\t\t\t" << streamName << " << templ->genText("
                 << viewDataName << ");\n"
                 << "\t\t}\n"
                 << "\t}\n";
            break;
        }

        default:
            break;
    }
}

static std::vector<Node> parseFile(std::string_view in)
{
    const TokenRule rules[] = {
        {"<%inc", "%>", NodeType::Include},
        {"<%c++", "%>", NodeType::CppCode},
        {"[[", "]]", NodeType::OutPut1},
        {"{%", "%}", NodeType::OutPut2},
        {"<%layout", "%>", NodeType::Layout},
        {"<%view", "%>", NodeType::View},
    };

    std::vector<Node> result;
    size_t i = 0;
    const size_t len = in.size();

    while (i < len)
    {
        size_t nearestPos = std::string_view::npos;
        const TokenRule *nearestRule = nullptr;

        for (const auto &rule : rules)
        {
            auto pos = in.find(rule.start, i);
            while (pos != std::string_view::npos)
            {
                if (pos == 0 || in[pos - 1] != '\\')
                {
                    if (pos < nearestPos)
                    {
                        nearestPos = pos;
                        nearestRule = &rule;
                    }
                    break;
                }
                pos = in.find(rule.start, pos + rule.start.size());
            }
        }

        if (!nearestRule)
        {
            result.emplace_back(std::string(in.substr(i)),
                                NodeType::NormalText);
            break;
        }

        if (nearestPos > i)
        {
            result.emplace_back(std::string(in.substr(i, nearestPos - i)),
                                NodeType::NormalText);
        }

        size_t contentStart = nearestPos + nearestRule->start.size();
        size_t endPos = contentStart;
        while ((endPos = in.find(nearestRule->end, endPos)) !=
               std::string_view::npos)
        {
            if (endPos == 0 || in[endPos - 1] != '\\')
                break;
            endPos += nearestRule->end.size();
        }

        if (endPos == std::string_view::npos)
        {
            std::cerr << "ERROR: tag " << nearestRule->start << " not closed\n";
            exit(1);
        }

        result.emplace_back(std::string(
                                in.substr(contentStart, endPos - contentStart)),
                            nearestRule->type);
        i = endPos + nearestRule->end.size();
    }

    return result;
}

void create_view::handleCommand(std::vector<std::string> &parameters)
{
    for (auto iter = parameters.begin(); iter != parameters.end();)
    {
        const auto &arg = *iter;

        if (arg == "-o" || arg == "--output")
        {
            iter = parameters.erase(iter);
            if (iter != parameters.end())
            {
                outputPath_ = *iter;
                iter = parameters.erase(iter);
            }
            continue;
        }
        else if (arg == "-n" || arg == "--namespace")
        {
            iter = parameters.erase(iter);
            if (iter != parameters.end())
            {
                namespaces_ = drogon::utils::splitString(*iter, "::");
                iter = parameters.erase(iter);
            }
            continue;
        }
        else if (arg == "--path-to-namespace")
        {
            iter = parameters.erase(iter);
            pathToNamespaceFlag_ = true;
            continue;
        }
        else if (arg[0] == '-')
        {
            std::cerr << ARGS_ERROR_STR << std::endl;
            return;
        }
        ++iter;
    }
    createViewFiles(parameters);
}

void create_view::createViewFiles(std::vector<std::string> &cspFileNames)
{
    for (auto &fileName : cspFileNames)
    {
        if (fileName.size() <= 4 ||
            fileName.substr(fileName.size() - 4) != ".csp")
        {
            std::cerr << "ERROR: filename should ends with .csp" << std::endl;
            exit(1);
        }
        if (createViewFile(fileName) != 0)
        {
            exit(1);
        }
    }
}

int create_view::createViewFile(const std::string &script_filename)
{
    fs::path inputPath(script_filename);
    inputPath = inputPath.lexically_normal();

    std::cout << "create HttpView Class file by " << inputPath << std::endl;

    if (pathToNamespaceFlag_ && inputPath.has_parent_path())
    {
        auto parent = inputPath.parent_path();
        std::vector<fs::path> parts(parent.begin(), parent.end());
        auto it = parts.begin();
#ifdef _WIN32
        if (it != parts.end())
        {
            std::string first = it->string();
            if (first.size() == 2 && std::isalpha(first[0]) && first[1] == ':')
            {
                namespaces_.emplace_back(1, first[0]);
                ++it;
                if (it != parts.end() && it->string().size() == 1 &&
                    it->string()[0] == fs::path::preferred_separator)
                {
                    ++it;
                }
            }
        }
#else
        // POSIX only: skip leading root separator
        if (it != parts.end() && it->string().size() == 1 &&
            it->string()[0] == fs::path::preferred_separator)
        {
            ++it;
        }
#endif
        for (; it != parts.end(); ++it)
        {
            std::string seg = it->string();
            std::replace(seg.begin(), seg.end(), '.', '_');
            namespaces_.push_back(seg);
        }
    }

    std::string npPrefix;
    for (std::string &np : namespaces_)
    {
        npPrefix += np + "_";
    }

    std::ifstream infile(inputPath);
    if (!infile)
    {
        std::cerr << "ERROR: can't open file " << script_filename << "\n";
        return -1;
    }

    std::string className = inputPath.stem().string();
    std::cout << "className=" << className << std::endl;

    auto headerPath =
        fs::path(outputPath_) / (npPrefix + className + "." + headerExtension);
    auto sourcePath =
        fs::path(outputPath_) / (npPrefix + className + "." + sourceExtension);

    std::ofstream oHeadFile(headerPath);
    std::ofstream oSourceFile(sourcePath);
    if (!oHeadFile || !oSourceFile)
    {
        std::cerr << "ERROR: Can't open " << headerPath << " or " << sourcePath
                  << "\n";
        return -1;
    }

    newViewHeaderFile(oHeadFile, className);
    newViewSourceFile(oSourceFile, className, npPrefix, infile);
    return 0;
}

void create_view::newViewHeaderFile(std::ofstream &file,
                                    const std::string &className)
{
    file << "// this file is generated by program(drogon_ctl) automatically, "
            "don't modify it!\n"
         << "#pragma once\n"
         << "#include <drogon/DrTemplate.h>\n\n";
    for (std::string &np : namespaces_)
    {
        file << "namespace " << np << "\n{\n";
    }
    file << "class " << className << " : public drogon::DrTemplate<"
         << className << ">\n"
         << "{\npublic:\n\t" << className << "(){};\n\tvirtual ~" << className
         << "(){};\n\t"
         << "virtual std::string genText(const drogon::DrTemplateData &) "
            "override;\n};\n";

    for (size_t i = 0; i < namespaces_.size(); ++i)
    {
        file << "}\n";
    }
}

void create_view::newViewSourceFile(std::ofstream &file,
                                    const std::string &className,
                                    const std::string &namespacePrefix,
                                    std::ifstream &infile)
{
    std::string layoutName;
    const std::string viewDataName = className + "_view_data";
    const std::string streamName = className + "_tmp_stream";

    file << headers(namespacePrefix + className);

    std::stringstream ss;
    ss << infile.rdbuf();
    auto nodeList = parseFile(ss.str());

    for (auto &node : nodeList)
    {
        if (node.type == NodeType::Include)
        {
            outputNode(file, node);
        }
        else if (node.type == NodeType::Layout)
        {
            if (!layoutName.empty())
            {
                std::cerr << "ERROR: <%layout %> can only use once"
                          << std::endl;
                exit(1);
            }
            layoutName = cppStr(node.content);
        }
    }

    if (!namespaces_.empty())
    {
        file << "using namespace ";
        for (size_t i = 0; i < namespaces_.size(); ++i)
        {
            if (i > 0)
                file << "::";
            file << namespaces_[i];
        }
        file << ";\n";
    }
    file << "using namespace drogon;\n\n";

    file << "std::string " << className << "::genText(const DrTemplateData &"
         << viewDataName << ")\n{\n"
         << "\tdrogon::OStringStream " << streamName << ";\n";

    for (auto &node : nodeList)
    {
        if (node.type == NodeType::Include || node.type == NodeType::Layout)
        {
            continue;
        }
        outputNode(file, node, streamName, viewDataName);
    }

    if (layoutName.empty())
    {
        file << "\tstd::string ret{std::move(" << streamName << ".str())};\n"
             << "\treturn ret;\n}\n";
    }
    else
    {
        file << "\tauto templ = DrTemplateBase::newTemplate(\"" << layoutName
             << "\");\n"
             << "\tif (!templ)\n\t\treturn \"\";\n"
             << "\tHttpViewData data = " << viewDataName << ";\n"
             << "\tauto str = std::move(" << streamName << ".str());\n"
             << "\tif (!str.empty() && str.back() == "
                "'\\n')\n\t\tstr.pop_back();\n"
             << "\tdata[\"\"] = std::move(str);\n"
             << "\treturn templ->genText(data);\n"
             << "}\n";
    }
}
